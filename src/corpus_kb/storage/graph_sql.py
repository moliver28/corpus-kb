"""Shared graph traversal SQL builders (storage-portability program §5.2).

Pure functions that render ONE portable SQL shape for Postgres and DuckDB:
no engine branch, UUID columns always read through ``::text`` (PG casts the
uuid; DuckDB's VARCHAR is a no-op), list filters bind as one array param
(``= ANY($n)`` works on both engines), and every ordered query carries the
pinned total order ``(depth, name, entity_id)`` (zero-drift rule 9).

``neighbors_sql`` renders hops 1..3 as a fixed self-join chain over
``relations`` — one UNION ALL branch per depth, generated by a loop, so a
future hop-4 fast path is a constant change. ``traverse_sql`` renders a
``WITH RECURSIVE`` walk with a path-array cycle guard for depths past the
fast path. Table names stay unqualified (the DuckDB gateway guard rejects
``corpus.``; graph SQL is naturally unqualified).
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import cast

# The first-class fast path: hops 1-3 run the fixed self-join shape.
MAX_NEIGHBOR_HOPS = 3
# Traversal directions (neighbors only; traverse walks undirected).
DIRECTIONS = ("in", "out", "both")
DEFAULT_LIMIT = 100

_ROW_COLUMNS = "entity_id, name, entity_type, metadata, depth"

# The shared min-depth wrap: a node reachable by two paths keeps its
# shallowest depth; the row_number subquery form works on both engines
# (DuckDB has QUALIFY, Postgres does not).
_DEDUP_WRAP = """
SELECT {columns} FROM (
    SELECT {columns},
           row_number() OVER (
               PARTITION BY entity_id ORDER BY depth ASC, name ASC, entity_id ASC
           ) AS rn
    FROM (
{rows}
    ) hop_rows
) ranked
WHERE rn = 1
ORDER BY depth ASC, name ASC, entity_id ASC
LIMIT {limit}
"""


def _edge_predicate(relation: str, prev: str, direction: str) -> str:
    """The JOIN condition tying one edge to the previous hop's node."""
    if direction == "out":
        return f"{relation}.source_entity_id::text = {prev}.entity_id::text"
    if direction == "in":
        return f"{relation}.target_entity_id::text = {prev}.entity_id::text"
    return (
        f"({relation}.source_entity_id::text = {prev}.entity_id::text"
        f" OR {relation}.target_entity_id::text = {prev}.entity_id::text)"
    )


def _neighbor_expr(relation: str, prev: str, direction: str) -> str:
    """The neighbor-node expression for one edge (direction-aware)."""
    if direction == "out":
        return f"{relation}.target_entity_id::text"
    if direction == "in":
        return f"{relation}.source_entity_id::text"
    return (
        f"CASE WHEN {relation}.source_entity_id::text = {prev}.entity_id::text"
        f" THEN {relation}.target_entity_id::text"
        f" ELSE {relation}.source_entity_id::text END"
    )


def _bind_list(args: list[object], values: list[str] | None) -> str | None:
    """Append one array-bound param and return its ``$n`` name (or None)."""
    if not values:
        return None
    args.append(list(values))
    return f"${len(args)}"


def _hop_branch(
    depth: int,
    direction: str,
    relation_param: str | None,
    entity_param: str | None,
) -> str:
    """One UNION ALL branch: the fixed chain that reaches exactly ``depth``."""
    joins: list[str] = []
    wheres: list[str] = []
    for hop in range(1, depth + 1):
        prev = "s" if hop == 1 else f"x{hop - 1}"
        relation = f"r{hop}"
        node = f"x{hop}"
        joins.append(
            f"    JOIN relations {relation} ON {relation}.tenant_id = $1"
            f" AND {_edge_predicate(relation, prev, direction)}"
        )
        node_filters = f" AND {node}.entity_id::text <> $2"
        if entity_param is not None:
            node_filters += f" AND {node}.entity_type = ANY({entity_param})"
        joins.append(
            f"    JOIN entities {node} ON {node}.tenant_id = $1"
            f" AND {node}.entity_id::text = {_neighbor_expr(relation, prev, direction)}"
            f"{node_filters}"
        )
        if relation_param is not None:
            wheres.append(f"{relation}.relation_type = ANY({relation_param})")
    where = "s.entity_id::text = $2 AND s.tenant_id = $1"
    if wheres:
        where += " AND " + " AND ".join(wheres)
    return (
        f"SELECT DISTINCT {depth} AS depth, x{depth}.entity_id::text AS entity_id,"
        f" x{depth}.name AS name, x{depth}.entity_type AS entity_type,"
        f" x{depth}.metadata::text AS metadata\n"
        f"FROM entities s\n" + "\n".join(joins) + f"\nWHERE {where}"
    )


def neighbors_sql(
    hops: int,
    direction: str,
    tenant_id: str,
    entity_id: str,
    relation_types: list[str] | None = None,
    entity_types: list[str] | None = None,
    limit: int = DEFAULT_LIMIT,
) -> tuple[str, list[object]]:
    """Render the fixed-chain neighbor query for hops 1..3.

    Param order: $1 tenant_id, $2 start entity_id, then the optional
    relation-type and entity-type array params. Returns ``(sql, args)``;
    rows come back ordered ``(depth, name, entity_id)`` with each node at
    its shallowest depth.
    """
    if direction not in DIRECTIONS:
        raise ValueError(f"direction must be one of {DIRECTIONS}, got {direction!r}")
    depth = int(hops)
    if not 1 <= depth <= MAX_NEIGHBOR_HOPS:
        raise ValueError(f"hops must be between 1 and {MAX_NEIGHBOR_HOPS}, got {hops!r}")
    args: list[object] = [tenant_id, entity_id]
    relation_param = _bind_list(args, relation_types)
    entity_param = _bind_list(args, entity_types)
    branches = "\n    UNION ALL\n".join(
        _hop_branch(hop, direction, relation_param, entity_param) for hop in range(1, depth + 1)
    )
    sql = _DEDUP_WRAP.format(columns=_ROW_COLUMNS, rows=branches, limit=int(limit))
    return sql, args


_TRAVERSE_CTE = """
WITH RECURSIVE walk (entity_id, name, entity_type, metadata, depth, path) AS (
    SELECT s.entity_id::text, s.name, s.entity_type, s.metadata::text,
           0 AS depth, ARRAY[s.entity_id::text] AS path
    FROM entities s
    WHERE s.tenant_id = $1 AND s.entity_id::text = $2
  UNION ALL
    SELECT nb.entity_id::text, nb.name, nb.entity_type, nb.metadata::text,
           w.depth + 1, array_append(w.path, nb.entity_id::text)
    FROM walk w
    JOIN relations r ON r.tenant_id = $1
      AND ({edge})
      {relation_filter}
    JOIN entities nb ON nb.tenant_id = $1
      AND nb.entity_id::text = {neighbor}
      {entity_filter}
    WHERE w.depth < $3 AND NOT nb.entity_id::text = ANY(w.path)
)
"""


def traverse_sql(
    max_depth: int,
    tenant_id: str,
    entity_id: str,
    relation_types: list[str] | None = None,
    entity_types: list[str] | None = None,
    limit: int = DEFAULT_LIMIT,
) -> tuple[str, list[object]]:
    """Render the recursive walk for depths past the fast path.

    Param order: $1 tenant_id, $2 start entity_id, $3 max_depth, then the
    optional filter params. The ``path`` array is the cycle guard; the
    min-depth wrap keeps BFS semantics. Rows ordered ``(depth, name,
    entity_id)``; the start node is never a row.
    """
    depth = int(max_depth)
    if depth < 1:
        raise ValueError(f"max_depth must be 1 or more, got {max_depth!r}")
    args: list[object] = [tenant_id, entity_id, depth]
    relation_param = _bind_list(args, relation_types)
    entity_param = _bind_list(args, entity_types)
    # The walk is undirected: both edge orientations per step.
    edge = _edge_predicate("r", "w", "both")
    neighbor = _neighbor_expr("r", "w", "both")
    relation_filter = f"AND r.relation_type = ANY({relation_param})" if relation_param else ""
    entity_filter = f"AND nb.entity_type = ANY({entity_param})" if entity_param else ""
    cte = _TRAVERSE_CTE.format(
        edge=edge,
        neighbor=neighbor,
        relation_filter=relation_filter,
        entity_filter=entity_filter,
    )
    walk_rows = f"    SELECT {_ROW_COLUMNS} FROM walk WHERE depth >= 1"
    sql = cte + _DEDUP_WRAP.format(columns=_ROW_COLUMNS, rows=walk_rows, limit=int(limit))
    return sql, args


def traversal_row(row: Mapping[str, object]) -> dict[str, object]:
    """Shape one traversal row: parse metadata, keep the pinned keys.

    Accepts any key-addressable row (``asyncpg.Record`` on Postgres, a
    ``dict`` on DuckDB) — the access style both stores already share.
    """
    raw_metadata = row["metadata"]
    metadata: object = {}
    if raw_metadata:
        try:
            metadata = json.loads(str(raw_metadata))
        except (TypeError, ValueError):
            metadata = {}
    return {
        "entity_id": row["entity_id"],
        "name": row["name"],
        "entity_type": row["entity_type"],
        "metadata": metadata,
        "depth": cast(int, row["depth"]),
    }
